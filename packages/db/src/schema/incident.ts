// Incidents, their timeline and the deploy feed (T-202a, migration 0044). Mirrors the SQL by hand;
// the SQL file is the source of truth (CHECKs, the partitioned append-only timeline, foreign keys on
// `ticket.incident_id` and `alert.incident_id`).
import { sql } from 'drizzle-orm';
import {
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { users } from './auth.js';
import { kbArticle } from './kb.js';
import { organization, ticket } from './ticketing.js';
import { service } from './alerting.js';

const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

export const incident = pgTable(
  'incident',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    /** The human number (INC-12). Generated by the database; never repeats. */
    number: integer('number').generatedAlwaysAsIdentity(),
    title: text('title').notNull(),
    /** `SEV1` to `SEV4`. */
    severity: text('severity').notNull(),
    /** `investigating`, `identified`, `monitoring`, `resolved`. */
    status: text('status').notNull().default('investigating'),
    commanderId: uuid('commander_id').references(() => users.id, { onDelete: 'set null' }),
    rootCause: text('root_cause'),
    postmortemArticleId: uuid('postmortem_article_id').references(() => kbArticle.id, {
      onDelete: 'set null',
    }),
    /** `pending`, `created` (real, with ids), `mock` (a fake recorded it: no ids), `skipped`, `failed`. */
    discordThreadState: text('discord_thread_state').notNull().default('pending'),
    discordChannelId: text('discord_channel_id'),
    discordThreadId: text('discord_thread_id'),
    statusPageVisible: boolean('status_page_visible').notNull().default(false),
    startedAt: timestamptz('started_at').notNull().defaultNow(),
    resolvedAt: timestamptz('resolved_at'),
    createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex('incident_number_key').on(table.number),
    index('incident_open_idx')
      .on(table.startedAt.desc())
      .where(sql`${table.status} <> 'resolved'`),
    index('incident_list_idx').on(table.createdAt.desc(), table.id.desc()),
  ],
);

export const incidentService = pgTable(
  'incident_service',
  {
    incidentId: uuid('incident_id')
      .notNull()
      .references(() => incident.id, { onDelete: 'cascade' }),
    serviceId: uuid('service_id')
      .notNull()
      .references(() => service.id, { onDelete: 'cascade' }),
  },
  (table) => [
    primaryKey({ columns: [table.incidentId, table.serviceId] }),
    index('incident_service_service_idx').on(table.serviceId),
  ],
);

export const incidentOrg = pgTable(
  'incident_org',
  {
    incidentId: uuid('incident_id')
      .notNull()
      .references(() => incident.id, { onDelete: 'cascade' }),
    orgId: uuid('org_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'cascade' }),
    /** `manual` or `ticket` (inferred from a linked ticket). */
    source: text('source').notNull().default('manual'),
  },
  (table) => [primaryKey({ columns: [table.incidentId, table.orgId] })],
);

/** Append-only, partitioned by month. The partition key is part of the primary key. */
export const incidentTimeline = pgTable(
  'incident_timeline',
  {
    id: uuid('id').notNull().defaultRandom(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    incidentId: uuid('incident_id')
      .notNull()
      .references(() => incident.id, { onDelete: 'restrict' }),
    type: text('type').notNull(),
    actorType: text('actor_type').notNull(),
    actorId: text('actor_id'),
    payload: jsonb('payload')
      .$type<Record<string, unknown>>()
      .notNull()
      .default(sql`'{}'::jsonb`),
  },
  (table) => [
    primaryKey({ columns: [table.id, table.createdAt] }),
    index('incident_timeline_incident_idx').on(table.incidentId, table.createdAt),
  ],
);

/** What was deployed (R-5.4). `(source, externalId)` is the idempotency key of the feed. */
export const deploy = pgTable(
  'deploy',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    serviceId: uuid('service_id').references(() => service.id, { onDelete: 'set null' }),
    serviceSlug: text('service_slug').notNull(),
    version: text('version').notNull(),
    env: text('env').notNull(),
    actor: text('actor'),
    /** `ci` or `github`. */
    source: text('source').notNull(),
    externalId: text('external_id').notNull(),
    startedAt: timestamptz('started_at'),
    finishedAt: timestamptz('finished_at'),
    url: text('url'),
    receivedAt: timestamptz('received_at').notNull().defaultNow(),
    /** Finished, else started, else when we heard. Generated by the database; the provider's time, for display. */
    occurredAt: timestamptz('occurred_at').generatedAlwaysAs(
      sql`COALESCE(finished_at, started_at, received_at)`,
    ),
  },
  (table) => [
    uniqueIndex('deploy_source_external_key').on(table.source, table.externalId),
    index('deploy_service_time_idx')
      .on(table.serviceId, table.occurredAt.desc())
      .where(sql`${table.serviceId} IS NOT NULL`),
    index('deploy_time_idx').on(table.occurredAt.desc()),
  ],
);

/**
 * One update drafted for the customers of an incident's tickets (T-202c, migration 0046). A person or the
 * AI drafts it; only a person sends it (`sentBy` and `confirmedRecipients` are required once it leaves
 * `draft`, by a CHECK).
 */
export const incidentComm = pgTable(
  'incident_comm',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    incidentId: uuid('incident_id')
      .notNull()
      .references(() => incident.id, { onDelete: 'restrict' }),
    body: text('body').notNull(),
    /** `human` or `ai`: who drafted it. */
    origin: text('origin').notNull(),
    /** `draft`, `sending`, `sent`, `cancelled`. */
    status: text('status').notNull().default('draft'),
    draftedBy: uuid('drafted_by').references(() => users.id, { onDelete: 'set null' }),
    sentBy: uuid('sent_by').references(() => users.id, { onDelete: 'set null' }),
    confirmedRecipients: integer('confirmed_recipients'),
    sentAt: timestamptz('sent_at'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
  },
  (table) => [index('incident_comm_incident_idx').on(table.incidentId, table.createdAt.desc())],
);

/** What happened for one ticket: `(commId, ticketId)` is unique, so a ticket is told once. */
export const incidentCommDelivery = pgTable(
  'incident_comm_delivery',
  {
    commId: uuid('comm_id')
      .notNull()
      .references(() => incidentComm.id, { onDelete: 'cascade' }),
    ticketId: uuid('ticket_id')
      .notNull()
      .references(() => ticket.id, { onDelete: 'restrict' }),
    /** `sent` or `failed`. */
    state: text('state').notNull(),
    messageId: uuid('message_id'),
    reason: text('reason'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ columns: [table.commId, table.ticketId] }),
    index('incident_comm_delivery_ticket_idx').on(table.ticketId),
  ],
);
