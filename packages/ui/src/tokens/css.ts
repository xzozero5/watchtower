import {
  COLOR_TOKENS,
  type ColorTokens,
  RADIUS_TOKENS,
  type ThemeName,
  TINT_IDS,
} from './colors.js';
import { DENSITY_TOKENS, type Density, type DensityTokens, MOTION_TOKENS } from './density.js';
import { SEVERITY_IDS } from './severity.js';

export const CSS_VAR_PREFIX = '--wt-';

const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** One entry per colour token: the CSS variable suffix and the value. */
function colorEntries(tokens: ColorTokens): [name: string, value: string][] {
  const entries: [string, string][] = [];
  for (const [key, value] of Object.entries(tokens)) {
    if (typeof value === 'string') entries.push([`color-${kebab(key)}`, value]);
  }
  for (const id of SEVERITY_IDS) {
    const { fg, bg, border } = tokens.severity[id];
    entries.push(
      [`color-severity-${id}-fg`, fg],
      [`color-severity-${id}-bg`, bg],
      [`color-severity-${id}-border`, border],
    );
  }
  for (const id of TINT_IDS) {
    const { fg, bg, icon } = tokens.tint[id];
    entries.push(
      [`color-tint-${id}-fg`, fg],
      [`color-tint-${id}-bg`, bg],
      [`color-tint-${id}-icon`, icon],
    );
  }
  entries.push(['color-chart-series', tokens.chart.series]);
  tokens.chart.ordinal.forEach((value, index) => {
    entries.push([`color-chart-ordinal-${String(index + 1)}`, value]);
  });
  tokens.avatar.forEach(({ fg, bg }, index) => {
    entries.push(
      [`color-avatar-${String(index + 1)}-fg`, fg],
      [`color-avatar-${String(index + 1)}-bg`, bg],
    );
  });
  return entries;
}

function densityEntries(tokens: DensityTokens): [name: string, value: string][] {
  return [
    ['font-scale', tokens.fontScale],
    ['row-height', tokens.rowHeight],
    ['control-height', tokens.controlHeight],
    ['pane-padding', tokens.panePadding],
    ['stack-gap', tokens.gap],
  ];
}

function radiusEntries(): [name: string, value: string][] {
  return Object.entries(RADIUS_TOKENS).map(([key, value]): [string, string] => [
    `radius-${key}`,
    value,
  ]);
}

const declarations = (entries: [string, string][], indent: string) =>
  entries.map(([name, value]) => `${indent}${CSS_VAR_PREFIX}${name}: ${value};`).join('\n');

/** Names of every colour variable, without the prefix. The same in light and dark. */
export function colorVariableNames(theme: ThemeName = 'light'): string[] {
  return colorEntries(COLOR_TOKENS[theme]).map(([name]) => name);
}

/**
 * Builds tokens.css, the single stylesheet with every design token as a CSS variable.
 *
 * Theme: light by default, dark when the OS asks for it, and an explicit `data-theme` attribute on
 * `<html>` (the user override) always wins. Density: `data-density="compact"` on `<html>`.
 * Reduced motion: durations drop to zero.
 */
export function buildTokensCss(): string {
  const light = COLOR_TOKENS.light;
  const dark = COLOR_TOKENS.dark;
  const motion = Object.entries(MOTION_TOKENS) as [string, string][];
  const motionEntries = (zero: boolean) =>
    motion.map(([key, value]): [string, string] => [`motion-${kebab(key)}`, zero ? '0ms' : value]);
  const compact: Density = 'compact';

  return [
    '/* Generated by scripts/build-css.mjs from src/tokens. Do not edit. */',
    ':root {',
    '  color-scheme: light;',
    declarations(
      [
        ...colorEntries(light),
        ...densityEntries(DENSITY_TOKENS.comfortable),
        ...radiusEntries(),
        ...motionEntries(false),
      ],
      '  ',
    ),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    "  :root:not([data-theme='light']) {",
    '    color-scheme: dark;',
    declarations(colorEntries(dark), '    '),
    '  }',
    '}',
    '',
    ":root[data-theme='dark'] {",
    '  color-scheme: dark;',
    declarations(colorEntries(dark), '  '),
    '}',
    '',
    `:root[data-density='${compact}'] {`,
    declarations(densityEntries(DENSITY_TOKENS[compact]), '  '),
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    declarations(motionEntries(true), '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Font sizes in rem of the 15px base: 12, 13, 14, 16 and 20 px. */
const TYPE_SCALE = {
  xs: '0.8rem',
  sm: '0.8667rem',
  base: '0.9333rem',
  lg: '1.0667rem',
  xl: '1.3333rem',
} as const;

/** The only shadow in the UI: popovers, menus, dialogs and toasts float, nothing else does. */
const OVERLAY_SHADOW = '0 1px 2px rgb(15 23 42 / 0.08), 0 8px 24px -4px rgb(15 23 42 / 0.18)';

/** The one soft lift besides overlays: the AI brief. Barely there. */
const SOFT_SHADOW = '0 1px 2px rgb(15 23 42 / 0.05), 0 4px 14px -6px rgb(15 23 42 / 0.12)';

const SANS_STACK =
  "'Inter Variable', 'Noto Sans Thai Variable', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif";
const MONO_STACK = "ui-monospace, 'SFMono-Regular', Menlo, Consolas, monospace";

/**
 * Builds tailwind-theme.css: maps the variables onto Tailwind v4 theme names so utilities such as
 * `bg-surface`, `text-muted-foreground` and `border-sev-p1-border` follow the active theme.
 * Import it after `@import 'tailwindcss'`.
 */
export function buildTailwindThemeCss(): string {
  const colorMap: [string, string][] = colorVariableNames().map((name) => {
    const utility = name.replace(/^color-/, '').replace(/^severity-/, 'sev-');
    return [`--color-${utility}`, `var(${CSS_VAR_PREFIX}${name})`];
  });
  // 12 / 13 / 14 / 16 / 20 px at the 15px comfortable base (docs/design/ui-refresh-2026-11.md
  // section 3.5). Line heights stay at 1.5 or more so Thai marks never collide.
  const typeScale: [string, string][] = Object.entries(TYPE_SCALE).flatMap(([name, rem]) => [
    [`--text-${name}`, rem],
    [`--text-${name}--line-height`, name === 'xl' ? '1.4' : '1.5'],
  ]);
  const spacing: [string, string][] = [
    ['--spacing-row', `var(${CSS_VAR_PREFIX}row-height)`],
    ['--spacing-control', `var(${CSS_VAR_PREFIX}control-height)`],
    ['--spacing-pane', `var(${CSS_VAR_PREFIX}pane-padding)`],
    ['--spacing-stack', `var(${CSS_VAR_PREFIX}stack-gap)`],
  ];
  const fonts: [string, string][] = [
    ['--font-sans', SANS_STACK],
    ['--font-mono', MONO_STACK],
  ];
  // Rounder everywhere (docs/design/friendly-polish.md section 2): the default md / lg / xl steps
  // become the control, card and dialog radii, so every existing `rounded-md|lg|xl` follows.
  const radii: [string, string][] = [
    ['--radius-md', `var(${CSS_VAR_PREFIX}radius-control)`],
    ['--radius-lg', `var(${CSS_VAR_PREFIX}radius-card)`],
    ['--radius-xl', `var(${CSS_VAR_PREFIX}radius-dialog)`],
    ['--radius-control', `var(${CSS_VAR_PREFIX}radius-control)`],
    ['--radius-card', `var(${CSS_VAR_PREFIX}radius-card)`],
    ['--radius-dialog', `var(${CSS_VAR_PREFIX}radius-dialog)`],
  ];
  const effects: [string, string][] = [
    ['--shadow-overlay', OVERLAY_SHADOW],
    ['--shadow-soft', SOFT_SHADOW],
    [
      '--animate-check-pop',
      `wt-check-pop var(${CSS_VAR_PREFIX}motion-duration-base) ease-out both`,
    ],
    // Durations come from the motion tokens, which drop to zero under prefers-reduced-motion.
    ['--animate-pop-in', `wt-pop-in var(${CSS_VAR_PREFIX}motion-duration-base) ease-out both`],
    ['--animate-fade-in', `wt-fade-in var(${CSS_VAR_PREFIX}motion-duration-base) ease-out both`],
    [
      '--animate-slide-in-right',
      `wt-slide-in-right var(${CSS_VAR_PREFIX}motion-duration-base) ease-out both`,
    ],
  ];
  const lines = [...colorMap, ...typeScale, ...spacing, ...radii, ...fonts, ...effects].map(
    ([name, value]) => `  ${name}: ${value};`,
  );
  return [
    '/* Generated by scripts/build-css.mjs from src/tokens. Do not edit. */',
    '/* The app imports the font files itself: Inter Variable and Noto Sans Thai Variable. */',
    '@theme inline {',
    ...lines,
    '}',
    '',
    '/* Popovers and menus rise 4px, panels slide 8px, both fade in. */',
    '@keyframes wt-pop-in {',
    '  from { opacity: 0; transform: translateY(4px) scale(0.98); }',
    '  to { opacity: 1; transform: none; }',
    '}',
    '@keyframes wt-fade-in {',
    '  from { opacity: 0; }',
    '  to { opacity: 1; }',
    '}',
    '/* A check mark pops when something succeeds (approve, resolve). */',
    '@keyframes wt-check-pop {',
    '  0% { opacity: 0; transform: scale(0.6); }',
    '  60% { opacity: 1; transform: scale(1.15); }',
    '  100% { opacity: 1; transform: none; }',
    '}',
    '@keyframes wt-slide-in-right {',
    '  from { opacity: 0; transform: translateX(8px); }',
    '  to { opacity: 1; transform: none; }',
    '}',
    '',
  ].join('\n');
}
