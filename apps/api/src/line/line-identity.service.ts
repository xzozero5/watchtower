import { randomBytes } from 'node:crypto';

import { Inject, Injectable } from '@nestjs/common';
import { line } from '@watchtower/channels';
import { schema } from '@watchtower/db';
import { isDomainError, type Actor, type Domain } from '@watchtower/domain';
import type { LineLinkCodeResult } from '@watchtower/shared';
import { and, arrayContains, eq } from 'drizzle-orm';

import type { Principal } from '../auth/principal.js';
import { TokenService } from '../auth/token.service.js';
import { APP_CONFIG, type ApiConfig } from '../config/config.js';
import { domainContext, markAudited, settle } from '../domain/domain-context.js';
import { translating } from '../domain/domain-errors.js';
import { DOMAIN } from '../domain/domain.module.js';
import { LOGGER, type AppLogger } from '../logging/logger.js';
import type { UnitOfWork } from '../realtime/unit-of-work.js';
import { UnitOfWorkService } from '../realtime/unit-of-work.js';
import { LINE_LOGIN_PROVIDER } from './line-login.js';

const STATE_PURPOSE = 'line-login-state';
const STATE_TTL_SECONDS = 600;

export type LoginFailure =
  | 'login_unavailable'
  | 'state_invalid'
  | 'denied'
  | 'exchange_failed'
  | 'no_contact'
  | 'already_linked';

export type LoginOutcome =
  { readonly status: 'linked' } | { readonly status: 'failed'; readonly reason: LoginFailure };

/** Who a LINE user is: link codes from staff, and LINE Login for a signed-in client (R-2.11). */
@Injectable()
export class LineIdentityService {
  constructor(
    @Inject(DOMAIN) private readonly domain: Domain,
    @Inject(UnitOfWorkService) private readonly uow: UnitOfWorkService,
    @Inject(TokenService) private readonly tokens: TokenService,
    @Inject(APP_CONFIG) private readonly config: ApiConfig,
    @Inject(LOGGER) private readonly logger: AppLogger,
    @Inject(LINE_LOGIN_PROVIDER) private readonly provider: line.LineLoginProvider | null,
  ) {}

  get loginAvailable(): boolean {
    return this.provider !== null;
  }

  private get redirectUri(): string {
    return new URL('/v1/line/login/callback', this.config.API_URL).toString();
  }

  /** A one-time code for a contact, generated by staff (R-2.11 route b). */
  issueLinkCode(contactId: string, actor: Actor): Promise<LineLinkCodeResult> {
    return this.uow.run((uow: UnitOfWork) =>
      translating(async () => {
        const issued = settle(
          uow,
          await this.domain.identity.issueLineLinkCode(uow.tx, domainContext(this.domain, actor), {
            contactId,
          }),
        );
        return {
          code: issued.code,
          expiresAt: issued.expiresAt.toISOString(),
          contactId: issued.contactId,
        };
      }),
    );
  }

  /** The URL of the LINE Login consent screen for the signed-in client. Null when LINE Login is off. */
  async startLogin(principal: Principal): Promise<string | null> {
    if (this.provider === null) return null;
    const nonce = randomBytes(16).toString('base64url');
    // The state is bound to the signed-in user: a callback replayed in another person's session is refused.
    const state = await this.tokens.signCookieValue(
      STATE_PURPOSE,
      { uid: principal.userId, nonce },
      STATE_TTL_SECONDS,
    );
    return this.provider.authorizeUrl({ state, nonce, redirectUri: this.redirectUri });
  }

  /** Completes LINE Login: links the LINE account to the signed-in client's contact. */
  async finishLogin(
    principal: Principal,
    query: {
      readonly code?: string | undefined;
      readonly state: string;
      readonly error?: string | undefined;
    },
  ): Promise<LoginOutcome> {
    if (this.provider === null) return { status: 'failed', reason: 'login_unavailable' };
    const saved = await this.tokens.verifyCookieValue(STATE_PURPOSE, query.state);
    const nonce = saved?.nonce;
    if (saved?.uid !== principal.userId || typeof nonce !== 'string') {
      return { status: 'failed', reason: 'state_invalid' };
    }
    if (query.error !== undefined || query.code === undefined) {
      return { status: 'failed', reason: 'denied' };
    }
    let lineUserId: string;
    try {
      const identity = await this.provider.exchange({
        code: query.code,
        nonce,
        redirectUri: this.redirectUri,
      });
      lineUserId = identity.userId;
    } catch (error) {
      this.logger.warn(
        { failure: error instanceof line.LineLoginError ? error.failure : 'error' },
        'LINE Login exchange failed',
      );
      return { status: 'failed', reason: 'exchange_failed' };
    }
    const actor: Actor = { type: 'user', id: principal.userId };
    try {
      await this.uow.run(async (uow) => {
        const contactId = await this.contactOf(uow, principal, actor);
        if (contactId === null) throw new NoContact();
        settle(
          uow,
          await this.domain.identity.linkLineUser(uow.tx, domainContext(this.domain, actor), {
            contactId,
            lineUserId,
            via: 'line_login',
          }),
        );
      });
      return { status: 'linked' };
    } catch (error) {
      if (error instanceof NoContact) return { status: 'failed', reason: 'no_contact' };
      if (isDomainError(error) && error.code === 'conflict') {
        return { status: 'failed', reason: 'already_linked' };
      }
      throw error;
    }
  }

  /** The signed-in client's own contact: their email in their organization, created on first use. */
  private async contactOf(
    uow: UnitOfWork,
    principal: Principal,
    actor: Actor,
  ): Promise<string | null> {
    if (principal.orgId === null) return null;
    const email = principal.email.trim().toLowerCase();
    const [existing] = await uow.tx
      .select({ id: schema.contact.id })
      .from(schema.contact)
      .where(
        and(
          eq(schema.contact.orgId, principal.orgId),
          arrayContains(schema.contact.emails, [email]),
        ),
      )
      .limit(1);
    if (existing !== undefined) return existing.id;
    const created = markAudited(
      await this.domain.contacts.findOrCreateByEmail(uow.tx, domainContext(this.domain, actor), {
        orgId: principal.orgId,
        email,
        name: principal.name,
      }),
    );
    return created.id;
  }

  /** Where the browser goes after the callback. */
  portalRedirect(outcome: LoginOutcome): string {
    const url = new URL('/portal', this.config.APP_URL);
    url.searchParams.set('line_login', outcome.status);
    if (outcome.status === 'failed') url.searchParams.set('reason', outcome.reason);
    return url.toString();
  }
}

class NoContact extends Error {}
